"use client";

import { useEffect, useRef, type ReactNode } from "react";
import { cn } from "@/lib/utils";

interface RevealProps {
  children: ReactNode;
  className?: string;
  delay?: number;
}

/**
 * Fade-in saat masuk layar. Berbeda dari pola `initial="hidden"` lama: isi
 * dirender terlihat di HTML server, jadi tetap terbaca tanpa JavaScript, saat
 * dicetak, dan oleh crawler. Hanya elemen yang berada di bawah layar saat
 * hidrasi yang disembunyikan sebentar, dan mereka belum terlihat pengunjung.
 * Status disimpan di atribut `data-reveal` (gaya di globals.css), bukan state
 * React, supaya tidak memicu render ulang.
 */
export function Reveal({ children, className, delay = 0 }: RevealProps) {
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    if (el.getBoundingClientRect().top < window.innerHeight) return;

    el.dataset.reveal = "pending";
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          el.dataset.reveal = "shown";
          io.disconnect();
        }
      },
      { rootMargin: "0px 0px -8% 0px" }
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
      className={cn("reveal", className)}
    >
      {children}
    </div>
  );
}
